import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
	    Scanner s= new Scanner(System.in);
	    int t=s.nextInt();
	    while(t-- > 0){
	        int x=s.nextInt();
	        int n=s.nextInt();
	        System.out.println((x/10)*n);
	    }
	}
}
